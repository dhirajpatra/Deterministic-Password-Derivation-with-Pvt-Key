"""Writes THIRD_PARTY_LICENSES.txt: the license notices of every Rust crate that the pwdx CLI is built from.

MIT, Apache-2.0 and BSD licenses require their notice to accompany binary redistributions. Run from anywhere; needs
`cargo` and a populated cargo registry (run `cargo fetch` or build once first).
Usage: python3 scripts/gen_third_party_licenses.py [output-file] [package]   (defaults: THIRD_PARTY_LICENSES.txt, pwdx)
"""
import json
import os
import re
import subprocess
import sys

root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "THIRD_PARTY_LICENSES.txt")
target_pkg = sys.argv[2] if len(sys.argv) > 2 else "pwdx"

meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=root))
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
start = next(p["id"] for p in meta["packages"] if p["name"] == target_pkg)

seen, stack = set(), [start]
while stack:
    pid = stack.pop()
    if pid in seen:
        continue
    seen.add(pid)
    for dep in nodes[pid]["deps"]:
        # skip dev-only dependencies (kind == "dev"); keep normal and build dependencies
        if any(k["kind"] != "dev" for k in dep["dep_kinds"]):
            stack.append(dep["pkg"])

first_party = {p["id"] for p in meta["packages"] if p["source"] is None}
LICENSE_FILE = re.compile(r"^(licen[sc]e|copying|unlicense|notice|copyright)([-_.].*)?$", re.I)

with open(out_path, "w", encoding="utf-8") as out:
    out.write(f"Third-party licenses for the crates compiled into `{target_pkg}`.\n")
    out.write("Generated by scripts/gen_third_party_licenses.py. Each crate keeps its own license.\n\n")
    count = 0
    for pid in sorted(seen - first_party, key=lambda i: (pkgs[i]["name"], pkgs[i]["version"])):
        p = pkgs[pid]
        folder = os.path.dirname(p["manifest_path"])
        files = sorted(f for f in os.listdir(folder) if LICENSE_FILE.match(f) and os.path.isfile(os.path.join(folder, f)))
        out.write("=" * 78 + "\n")
        out.write(f"{p['name']} {p['version']}  ({p.get('license') or 'see license file'})\n")
        if p.get("repository"):
            out.write(f"{p['repository']}\n")
        out.write("=" * 78 + "\n")
        if not files:
            out.write("(no license file shipped in the crate; declared license shown above)\n\n")
        for f in files:
            out.write(f"--- {f} ---\n")
            out.write(open(os.path.join(folder, f), encoding="utf-8", errors="replace").read().rstrip() + "\n\n")
        count += 1
print(f"wrote {out_path}: {count} crates")
