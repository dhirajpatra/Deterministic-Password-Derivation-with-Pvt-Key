"""Regenerates app/integration_test/vectors_data.dart from testvectors/v1.json (single source of truth).
CI re-runs this and fails if the committed file differs."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "..", "..", "testvectors", "v1.json"), encoding="utf-8").read()
json.loads(src)
assert "'''" not in src
out = os.path.join(here, "..", "integration_test", "vectors_data.dart")
with open(out, "w", encoding="utf-8") as f:
    f.write("// GENERATED by tool/gen_vectors_dart.py from ../testvectors/v1.json. Do not edit by hand.\n"
            "// ignore_for_file: lines_longer_than_80_chars\n\n"
            "const String vectorsJson = r'''\n" + src + "''';\n")
print("wrote", out)
